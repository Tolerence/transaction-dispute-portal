CREATE TABLE transactions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id   VARCHAR(64)    NOT NULL,
    reference     VARCHAR(64)    NOT NULL UNIQUE,
    merchant_name VARCHAR(200)   NOT NULL,
    amount        NUMERIC(19, 2) NOT NULL,
    currency      CHAR(3)        NOT NULL,
    status        VARCHAR(20)    NOT NULL,
    booked_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT chk_transactions_status CHECK (status IN ('PENDING', 'POSTED', 'REVERSED'))
);

CREATE INDEX idx_transactions_customer_booked ON transactions (customer_id, booked_at);

CREATE TABLE disputes (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id  BIGINT       NOT NULL REFERENCES transactions (id),
    customer_id     VARCHAR(64)  NOT NULL,
    reason          VARCHAR(40)  NOT NULL,
    description     VARCHAR(1000) NOT NULL,
    status          VARCHAR(20)  NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    closed_at       TIMESTAMP WITH TIME ZONE,
    version         BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT chk_disputes_status CHECK (status IN ('SUBMITTED', 'UNDER_REVIEW', 'ACCEPTED', 'REJECTED', 'WITHDRAWN'))
);

CREATE INDEX idx_disputes_customer_created ON disputes (customer_id, created_at);
CREATE INDEX idx_disputes_transaction ON disputes (transaction_id);

CREATE TABLE dispute_events (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dispute_id    BIGINT       NOT NULL REFERENCES disputes (id),
    from_status   VARCHAR(20),
    to_status     VARCHAR(20)  NOT NULL,
    actor         VARCHAR(64)  NOT NULL,
    note          VARCHAR(500),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_dispute_events_dispute ON dispute_events (dispute_id, created_at);
